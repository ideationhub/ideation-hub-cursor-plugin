#!/usr/bin/env node

import { promises as fs } from "node:fs";
import path from "node:path";
import process from "node:process";

const repoRoot = process.cwd();

const units = [
  {
    id: "ideation-hub-platform",
    sourceDir: "plugins/ideation-hub-platform/skills/ideation-hub-platform",
  },
  {
    id: "ideation-hub-developer",
    sourceDir: "plugins/ideation-hub-developer/skills/ideation-hub-developer",
  },
  {
    id: "ideation-hub-requirements",
    sourceDir: "plugins/ideation-hub-requirements/skills/ideation-hub-requirements-agent",
  },
];

function outputPath(id) {
  return path.join(repoRoot, "docs", "instructions", `${id}.md`);
}

async function readText(filePath) {
  const text = await fs.readFile(filePath, "utf8");
  return text.replace(/\r\n/g, "\n").replace(/\s+$/u, "");
}

async function buildUnit(unit) {
  const sourceRoot = path.join(repoRoot, unit.sourceDir);
  const sections = [];
  sections.push(await readText(path.join(sourceRoot, "SKILL.md")));

  const referencesDir = path.join(sourceRoot, "references");
  const names = (await fs.readdir(referencesDir))
    .filter((name) => name.endsWith(".md"))
    .sort();

  for (const name of names) {
    const body = await readText(path.join(referencesDir, name));
    sections.push(`# Source: references/${name}\n\n${body}`);
  }

  const listed = ["SKILL.md", ...names.map((name) => `references/${name}`)].join(", ");
  const banner = [
    "<!-- Generated by scripts/build-instructions.mjs. Do not edit this file. -->",
    "",
    `This file concatenates the ${unit.id} instructions from \`${unit.sourceDir}\`.`,
    `Sources, in order: ${listed}.`,
    "Relative links below refer to those source files, not to this document.",
    "Regenerate with `node scripts/build-instructions.mjs`.",
    "",
  ].join("\n");

  return `${banner}${sections.join("\n\n")}\n`;
}

async function main() {
  const check = process.argv.includes("--check");
  const mismatches = [];

  await fs.mkdir(path.join(repoRoot, "docs", "instructions"), { recursive: true });

  for (const unit of units) {
    const next = await buildUnit(unit);
    const target = outputPath(unit.id);
    if (check) {
      let current = "";
      try {
        current = await fs.readFile(target, "utf8");
      } catch {
        mismatches.push(`${path.relative(repoRoot, target)} is missing`);
        continue;
      }
      if (current !== next) {
        mismatches.push(`${path.relative(repoRoot, target)} is out of date`);
      }
    } else {
      await fs.writeFile(target, next);
    }
  }

  if (mismatches.length > 0) {
    console.error("Generated instructions are out of date:");
    for (const line of mismatches) {
      console.error(`- ${line}`);
    }
    console.error("Run: node scripts/build-instructions.mjs");
    process.exit(1);
  }

  if (check) {
    console.log("Generated instructions are up to date.");
  } else {
    console.log("Wrote docs/instructions/*.md");
  }
}

await main();
